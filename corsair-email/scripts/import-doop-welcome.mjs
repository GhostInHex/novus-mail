import { launchBrowser } from "./browser.mjs";
import { appStyle, frameForTheme } from "./doop-source.mjs";
import fs from "node:fs";
const browser = await launchBrowser();
const page = await browser.newPage();
const selectors = {
  ".doop-source-welcome": '[data-node-label="AI Welcome Content"]',
  ".doop-source-welcome h2":
    '[data-node-label="AI Welcome Content"] :text-is("What needs your attention?")',
  ".doop-source-welcome > p":
    '[data-node-label="AI Welcome Content"] :text-is("Ask about your inbox, prepare a reply, or find time to meet.")',
  ".doop-source-welcome ul": '[data-node-label="AI Suggestions"]',
  ".doop-source-welcome button": '[data-node-label="Suggestion Button"]',
  ".doop-source-welcome button > span": '[data-node-label="Suggestion Text"]',
  '.doop-ai-panel [data-slot="dialog-title"]':
    '[data-node-label="Assistant Header"] :text-is("Ask your inbox")',
};
let css =
  "/* Generated by scripts/import-doop-welcome.mjs from both source artboards. */\n";
try {
  for (const theme of ["light", "dark"]) {
    const frame = frameForTheme("sa5ThibhQK", theme);
    await page.setContent(
      fs.readFileSync(`design/doop/screens/${frame.id}.html`, "utf8"),
    );
    for (const [target, selector] of Object.entries(selectors)) {
      const source = await page.locator(selector).first().getAttribute("style");
      if (!source) throw Error(`${frame.id}: ${selector}`);
      let style = appStyle(source);
      if (target.includes("dialog-title"))
        style = style.replace(
          "display:block",
          "display:flex;align-items:center;gap:12px",
        );
      css += `/* ${frame.id}: ${selector} */\n:where(html.${theme}) ${target} { ${style} }\n`;
    }
  }
  css += `
.doop-source-welcome ul { list-style: none; padding: 0; }
.doop-source-welcome li { width: 100%; }
.doop-source-welcome button { width: 100%; text-align: left; cursor: pointer; }
.doop-source-welcome button > span { flex: 1; }
.doop-source-welcome button > svg { flex-shrink: 0; }
.doop-source-welcome button:hover { background: var(--accent); }
.doop-source-welcome button:focus-visible { outline: 2px solid var(--ring); outline-offset: 2px; }
.doop-source-welcome button:disabled { opacity: .5; cursor: default; }
`;
  fs.writeFileSync("src/components/doop/ai-welcome.css", css);
} finally {
  await browser.close();
}
